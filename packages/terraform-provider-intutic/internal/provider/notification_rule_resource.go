func (r *notificationRuleResource) Configure(_ context.Context, req resource.ConfigureRequest, resp *resource.ConfigureResponse) {
	r.client = configuredClient(req.ProviderData, &resp.Diagnostics)
}

// ValidateConfig is requireChannelConfigKey: each channel needs its target.
func (r *notificationRuleResource) ValidateConfig(ctx context.Context, req resource.ValidateConfigRequest, resp *resource.ValidateConfigResponse) {
	var cfg notificationRuleModel
	resp.Diagnostics.Append(req.Config.Get(ctx, &cfg)...)
	if resp.Diagnostics.HasError() || cfg.Channel.IsUnknown() {
		return
	}
	missing := func(attr, msg string) {
		resp.Diagnostics.AddAttributeError(path.Root(attr), "Missing channel target", msg)
	}
	switch cfg.Channel.ValueString() {
	case "slack":
		if cfg.SlackChannelID.IsNull() && cfg.SlackChannel.IsNull() {
			missing("slack_channel_id", "A slack rule needs slack_channel_id or slack_channel_name.")
		}
	case "email":
		if cfg.EmailRecipients.IsNull() {
			missing("email_recipients", "An email rule needs at least one email_recipients entry.")
		}
	case "webhook":
		if cfg.WebhookURL.IsNull() {
			missing("webhook_url", "A webhook rule needs webhook_url.")
		}
	case "pagerduty":
		if cfg.PagerdutyKey.IsNull() {
			missing("pagerduty_routing_key", "A pagerduty rule needs pagerduty_routing_key.")
		}
	}
}

// ModifyPlan keeps the signing secret across updates unless the rule becomes,
// or stops being, a webhook — the only changes that make the API issue or
// drop one (notificationHubService.ts updateRule).
func (r *notificationRuleResource) ModifyPlan(ctx context.Context, req resource.ModifyPlanRequest, resp *resource.ModifyPlanResponse) {
	if req.State.Raw.IsNull() || req.Plan.Raw.IsNull() {
		return
	}
	var plan, state notificationRuleModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}
	switch {
	case plan.Channel.Equal(state.Channel):
		plan.SigningSecret = state.SigningSecret
	case plan.Channel.ValueString() != "webhook":
		plan.SigningSecret = types.StringNull()
	default:
		plan.SigningSecret = types.StringUnknown()
	}
	resp.Diagnostics.Append(resp.Plan.Set(ctx, &plan)...)
}

func (m *notificationRuleModel) body(ctx context.Context, diags *diag.Diagnostics) map[string]any {
	cfg := map[string]any{}
	if !m.SlackChannelID.IsNull() {
		cfg["slackChannelId"] = m.SlackChannelID.ValueString()
	}
	if !m.SlackChannel.IsNull() {
		cfg["slackChannelName"] = m.SlackChannel.ValueString()
	}
	if v := listStrings(ctx, m.EmailRecipients, diags); v != nil {
		cfg["emailRecipients"] = v
	}
	if !m.WebhookURL.IsNull() {
		cfg["webhookUrl"] = m.WebhookURL.ValueString()
	}
	if !m.PagerdutyKey.IsNull() {
		cfg["pagerdutyRoutingKey"] = m.PagerdutyKey.ValueString()
	}
	filters := map[string]any{}
	if v := listStrings(ctx, m.Severity, diags); v != nil {
		filters["severity"] = v
	}
	if v := listStrings(ctx, m.HarnessType, diags); v != nil {
		filters["harnessType"] = v
	}
	if v := listStrings(ctx, m.UserID, diags); v != nil {
		filters["userId"] = v
	}
	return map[string]any{
		"eventType":       m.EventType.ValueString(),
		"channel":         m.Channel.ValueString(),
		"channelConfig":   cfg,
		"filters":         filters,
		"cooldownMinutes": m.CooldownMinutes.ValueInt64(),
		"enabled":         m.Enabled.ValueBool(),
	}
}

// maskedRoutingKey is the API's mask (notificationHubService.ts maskSecret).
func maskedRoutingKey(key string) string {
	runes := []rune(key)
	if len(runes) > 6 {
		runes = runes[:6]
	}
	return string(runes) + "…"
}

// applyTo copies the server's view. The routing key comes back masked: the
// configured key is kept when its mask matches, so only a key changed outside
// Terraform shows as a difference.
func (a *apiRule) applyTo(m *notificationRuleModel) {
	m.ID = types.StringValue(a.RuleID)
	m.EventType = types.StringValue(a.EventType)
	m.Channel = types.StringValue(a.Channel)
	m.SlackChannelID = stringOrNull(a.ChannelConfig.SlackChannelID)
	m.SlackChannel = stringOrNull(a.ChannelConfig.SlackChannelName)
	m.EmailRecipients = stringList(a.ChannelConfig.EmailRecipients)
	m.WebhookURL = stringOrNull(a.ChannelConfig.WebhookURL)
	switch masked := a.ChannelConfig.PagerdutyKey; {
	case masked == nil:
		m.PagerdutyKey = types.StringNull()
	case m.PagerdutyKey.IsNull() || maskedRoutingKey(m.PagerdutyKey.ValueString()) != *masked:
		m.PagerdutyKey = types.StringValue(*masked)
	}
	m.Severity = stringList(a.Filters.Severity)
	m.HarnessType = stringList(a.Filters.HarnessType)
	m.UserID = stringList(a.Filters.UserID)
	m.CooldownMinutes = types.Int64Value(a.CooldownMinutes)
	m.Enabled = types.BoolValue(a.Enabled)
	if a.SigningSecret != "" {
		m.SigningSecret = types.StringValue(a.SigningSecret)
	} else if a.Channel != "webhook" || m.SigningSecret.IsUnknown() {
		m.SigningSecret = types.StringNull()
	}
}

func (r *notificationRuleResource) Create(ctx context.Context, req resource.CreateRequest, resp *resource.CreateResponse) {
	var plan notificationRuleModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	if resp.Diagnostics.HasError() {
		return
	}
	var out apiRule
	if err := r.client.Post(ctx, rulesPath, plan.body(ctx, &resp.Diagnostics), &out); err != nil {
		resp.Diagnostics.AddError("Creating notification rule failed", err.Error())
		return
	}
	out.applyTo(&plan)
	resp.Diagnostics.Append(resp.State.Set(ctx, &plan)...)
}

func (r *notificationRuleResource) Read(ctx context.Context, req resource.ReadRequest, resp *resource.ReadResponse) {
	var state notificationRuleModel
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}
	var out struct {
		Rules []apiRule `json:"rules"`
	}
	if err := r.client.Get(ctx, rulesPath, &out); err != nil {
		resp.Diagnostics.AddError("Reading notification rules failed", err.Error())
		return
	}
	for i := range out.Rules {
		if out.Rules[i].RuleID == state.ID.ValueString() {
			out.Rules[i].applyTo(&state)
			resp.Diagnostics.Append(resp.State.Set(ctx, &state)...)
			return
		}
	}
	resp.State.RemoveResource(ctx)
}

func (r *notificationRuleResource) Update(ctx context.Context, req resource.UpdateRequest, resp *resource.UpdateResponse) {
	var plan, state notificationRuleModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}
	var out apiRule
	if err := r.client.Put(ctx, rulesPath+"/"+esc(state.ID.ValueString()), plan.body(ctx, &resp.Diagnostics), &out); err != nil {
		resp.Diagnostics.AddError("Updating notification rule failed", err.Error())
		return
	}
	out.applyTo(&plan)
	resp.Diagnostics.Append(resp.State.Set(ctx, &plan)...)
}

func (r *notificationRuleResource) Delete(ctx context.Context, req resource.DeleteRequest, resp *resource.DeleteResponse) {
	var state notificationRuleModel
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}
	err := r.client.Delete(ctx, rulesPath+"/"+esc(state.ID.ValueString()), nil)
	if err != nil && !client.IsNotFound(err) {
		resp.Diagnostics.AddError("Deleting notification rule failed", err.Error())
	}
}

func (r *notificationRuleResource) ImportState(ctx context.Context, req resource.ImportStateRequest, resp *resource.ImportStateResponse) {
	resp.Diagnostics.Append(resp.State.SetAttribute(ctx, path.Root("id"), req.ID)...)
}
