// Notification-rule routes: routes/notifications.ts (createRuleSchema,
// updateRuleSchema, requireChannelConfigKey).
var notificationChannels = []string{"slack", "email", "webhook", "pagerduty"}

const rulesPath = "/api/v1/notifications/rules"

type notificationRuleResource struct{ client *client.Client }

type notificationRuleModel struct {
	ID              types.String `tfsdk:"id"`
	EventType       types.String `tfsdk:"event_type"`
	Channel         types.String `tfsdk:"channel"`
	SlackChannelID  types.String `tfsdk:"slack_channel_id"`
	SlackChannel    types.String `tfsdk:"slack_channel_name"`
	EmailRecipients types.List   `tfsdk:"email_recipients"`
	WebhookURL      types.String `tfsdk:"webhook_url"`
	PagerdutyKey    types.String `tfsdk:"pagerduty_routing_key"`
	Severity        types.List   `tfsdk:"filter_severity"`
	HarnessType     types.List   `tfsdk:"filter_harness_type"`
	UserID          types.List   `tfsdk:"filter_user_id"`
	CooldownMinutes types.Int64  `tfsdk:"cooldown_minutes"`
	Enabled         types.Bool   `tfsdk:"enabled"`
	SigningSecret   types.String `tfsdk:"signing_secret"`
}

type apiChannelConfig struct {
	SlackChannelID   *string  `json:"slackChannelId,omitempty"`
	SlackChannelName *string  `json:"slackChannelName,omitempty"`
	EmailRecipients  []string `json:"emailRecipients,omitempty"`
	WebhookURL       *string  `json:"webhookUrl,omitempty"`
	PagerdutyKey     *string  `json:"pagerdutyRoutingKey,omitempty"`
}

type apiFilters struct {
	Severity    []string `json:"severity,omitempty"`
	HarnessType []string `json:"harnessType,omitempty"`
	UserID      []string `json:"userId,omitempty"`
}

type apiRule struct {
	RuleID          string           `json:"ruleId"`
	EventType       string           `json:"eventType"`
	Channel         string           `json:"channel"`
	ChannelConfig   apiChannelConfig `json:"channelConfig"`
	Filters         apiFilters       `json:"filters"`
	CooldownMinutes int64            `json:"cooldownMinutes"`
	Enabled         bool             `json:"enabled"`
	SigningSecret   string           `json:"signingSecret"`
}

func newNotificationRuleResource() resource.Resource { return &notificationRuleResource{} }

var (
	_ resource.ResourceWithImportState    = (*notificationRuleResource)(nil)
	_ resource.ResourceWithValidateConfig = (*notificationRuleResource)(nil)
	_ resource.ResourceWithModifyPlan     = (*notificationRuleResource)(nil)
)

func (r *notificationRuleResource) Metadata(_ context.Context, req resource.MetadataRequest, resp *resource.MetadataResponse) {
	resp.TypeName = req.ProviderTypeName + "_notification_rule"
}

