// SIEM destination routes: routes/siem.ts (CreateDestinationSchema,
// UpdateDestinationSchema, validateConfig, MASKED_FIELDS_BY_ADAPTER).
const siemPath = "/api/v1/siem/destinations"

var siemAdapters = []string{"syslog_cef", "webhook_https", "gcs", "s3", "splunk_hec", "datadog_logs"}

// siemSecretFields are the config fields the API masks on every read
// (MASKED_FIELDS_BY_ADAPTER), less `signingSecret`, which the API generates
// and never accepts. They live in `secret_config`, apart from `config`.
//
// Why two attributes: the API returns these fields as `********` plus the
// last four characters. Kept inside one JSON `config`, the whole attribute
// would have to be sensitive (hiding a webhook URL or bucket name in every
// plan) and the masked read would differ from the configuration on every
// refresh. Split out, `config` stays readable and compares exactly, and each
// secret is compared through its mask: a read whose mask matches the
// configured value keeps it, so only a secret changed outside Terraform shows
// as a difference.
var siemSecretFields = map[string][]string{
	"webhook_https": {"authHeaderValue"},
	"splunk_hec":    {"token"},
	"datadog_logs":  {"apiKey"},
	"gcs":           {"credentials"},
	"s3":            {"secretAccessKey"},
}

// siemSigningSecretField is generated by the API for a webhook destination,
// masked on reads, and ignored when sent.
const siemSigningSecretField = "signingSecret"

// siemRequiredFields is validateConfig: what each adapter cannot do without.
var siemRequiredFields = map[string][]string{
	"syslog_cef":    {"host", "port"},
	"webhook_https": {"webhookUrl"},
	"splunk_hec":    {"hecUrl", "token"},
	"datadog_logs":  {"apiKey"},
	"gcs":           {"bucketName"},
	"s3":            {"bucketName"},
}

func isSiemSecretField(adapter, field string) bool {
	return field == siemSigningSecretField || slices.Contains(siemSecretFields[adapter], field)
}

// siemMask is the API's maskConfig for one value. JavaScript measures and
// slices a string in UTF-16 code units, so this does too.
func siemMask(v string) string {
	u := utf16.Encode([]rune(v))
	if len(u) > 8 {
		return "********" + string(utf16.Decode(u[len(u)-4:]))
	}
	return "********"
}

