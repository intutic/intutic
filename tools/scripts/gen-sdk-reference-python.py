#!/usr/bin/env python3
"""Generate the Python SDK API reference for the docs site, from source.

Writes one Markdown page per public module of packages/intutic-clawde into
apps/docs/reference/sdk/python/, plus `sidebar.json`, which
apps/docs/.vitepress/config.ts reads. `pnpm gen:sdk-reference` runs this along
with the TypeScript half (gen-sdk-reference.mjs); `--check` writes nothing and
fails when the committed pages differ from what the source produces, which is
how CI keeps the reference from drifting.

The public API is a module's `__all__`. The documented modules are the two
package roots and every framework adapter; each must declare `__all__`, so a
new adapter cannot ship undocumented by accident.

The source is read statically with griffe (pinned in the package's dev
dependencies), never imported: the adapters subclass optional framework
classes, and importing them would make the reference depend on which extras
happen to be installed.

Usage (from packages/intutic-clawde, inside its Poetry environment):
    poetry run python ../../tools/scripts/gen-sdk-reference-python.py [--check] [--out DIR]
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PACKAGE_DIR = ROOT / "packages" / "intutic-clawde"
PACKAGE = "intutic_clawde"
OUT = ROOT / "apps" / "docs" / "reference" / "sdk" / "python"
LINK_BASE = "/reference/sdk/python"

# Module path -> whether it is a package. A page's file mirrors the module
# path (dots would read as a file extension in a link), and a package's page
# is the index of its directory.
PACKAGES: dict[str, bool] = {}


def page_file(path: str) -> str:
    rel = path.replace(".", "/")
    return f"{rel}/index.md" if PACKAGES[path] else f"{rel}.md"


def page_link(path: str) -> str:
    rel = path.replace(".", "/")
    return f"{LINK_BASE}/{rel}/" if PACKAGES[path] else f"{LINK_BASE}/{rel}"

# Modules whose `__all__` is documented. A trailing ".*" documents every
# module directly inside that package (the package page itself lists them).
PUBLIC_MODULES = ["intutic_clawde", "intutic_clawde.gate", "intutic_clawde.gate.adapters.*"]

HEADER = (
    "<!-- Generated by tools/scripts/gen-sdk-reference-python.py from packages/intutic-clawde. "
    "Do not edit: change the docstring and run `pnpm gen:sdk-reference`. -->\n\n"
)


def load_griffe():
    try:
        import griffe  # noqa: PLC0415
    except ImportError:
        sys.exit(
            "gen-sdk-reference-python: griffe is not installed. Run it in the package's Poetry "
            "environment: cd packages/intutic-clawde && poetry install --with dev && "
            "poetry run python ../../tools/scripts/gen-sdk-reference-python.py"
        )
    return griffe


def first_definition_wins(griffe):
    """A class defined twice in one module keeps its first definition.

    Two adapters define their class under `if _HAS_<framework>:` and, in the
    `else:` branch, a stub that only raises. A static reader visits both and
    keeps the last, which would document the stub; the real class is first.
    """

    class FirstDefinitionWins(griffe.Extension):
        def __init__(self) -> None:
            super().__init__()
            self.first: dict[str, object] = {}
            self.redefined: list[str] = []

        def on_class_instance(self, *, node, cls, agent, **kwargs) -> None:  # noqa: ARG002
            if cls.path in self.first:
                self.redefined.append(cls.path)
            else:
                self.first[cls.path] = cls

        def restore(self, root) -> None:
            for path in self.redefined:
                first = self.first[path]
                parent_path, name = path.rsplit(".", 1)
                root.modules_collection.get_member(parent_path).set_member(name, first)

    return FirstDefinitionWins()


# ---------------------------------------------------------------- docstrings

# A code span may wrap onto the next line, but not across a blank one.
CODE_SPAN = re.compile(r"(`+)((?:(?!\n[ \t]*\n)[\s\S])+?)\1")


def escape_prose(text: str) -> str:
    """Make docstring prose safe for VitePress, leaving code spans alone.

    VitePress compiles every page as a Vue template: a bare `<server>` is an
    unclosed element and `{{ x }}` an interpolation, and a line starting with
    `#` is a heading. reST ``literal`` spans become Markdown `literal`.
    """
    out, last = [], 0
    for m in CODE_SPAN.finditer(text):
        out.append(_escape_plain(text[last:m.start()]))
        tick, inner = m.group(1), m.group(2)
        out.append(f"`{inner}`" if len(tick) == 2 and "`" not in inner else m.group(0))
        last = m.end()
    out.append(_escape_plain(text[last:]))
    return "\n".join("\\" + ln if ln.lstrip().startswith("#") else ln for ln in "".join(out).split("\n"))


def _escape_plain(s: str) -> str:
    return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace("{{", "&#123;&#123;")


def markdown(doc: str) -> str:
    """A docstring as Markdown: prose escaped, reST literal blocks fenced.

    A line ending in `::` introduces an indented literal block, which becomes
    a fenced block. An indented block after a blank line is already a code
    block in Markdown, so it is kept as it is.
    """
    lines = doc.splitlines()
    out: list[str] = []
    prose: list[str] = []

    def flush() -> None:
        if prose:
            out.append(escape_prose("\n".join(prose)))
            prose.clear()

    i = 0
    while i < len(lines):
        line = lines[i]
        if line.rstrip().endswith("::"):
            stripped = line.rstrip()[:-1]
            if stripped.strip() != ":":
                prose.append(stripped)
            flush()
            i += 1
            block: list[str] = []
            while i < len(lines) and (not lines[i].strip() or lines[i].startswith((" ", "\t"))):
                block.append(lines[i])
                i += 1
            while block and not block[-1].strip():
                block.pop()
            while block and not block[0].strip():
                block.pop(0)
            indent = min((len(b) - len(b.lstrip()) for b in block if b.strip()), default=0)
            out.append("\n".join(["", "```python", *[b[indent:] if b.strip() else "" for b in block], "```", ""]))
            continue
        after_blank = i == 0 or not lines[i - 1].strip()
        if line.startswith(("    ", "\t")) and after_blank:
            flush()
            block = []
            while i < len(lines) and (not lines[i].strip() or lines[i].startswith(("    ", "\t"))):
                block.append(lines[i])
                i += 1
            out.append("\n".join(block))
            continue
        prose.append(line)
        i += 1
    flush()
    return "\n".join(out).strip() + "\n"


def summary(doc: str | None) -> str:
    if not doc:
        return ""
    para = doc.strip().split("\n\n")[0].replace("\n", " ")
    m = re.match(r"(.+?[.!?])(\s|$)", para)
    return escape_prose(m.group(1) if m else para)


# ---------------------------------------------------------------- signatures


def expr(value) -> str:
    return "" if value is None else str(value)


LITERAL = re.compile(r"""^(-?[0-9][0-9_.eE+-]*|True|False|None|'[^'\\]*'|"[^"\\]*")$""")


def default_text(p, fn) -> str:
    """A parameter's default as Python evaluates it: a module constant whose
    value is a plain literal shows that value, as `inspect.signature` would."""
    text = str(p.default)
    if re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", text) and text not in ("True", "False", "None"):
        module = fn.module
        member = module.members.get(text)
        if member is not None and not member.is_alias and member.kind.value == "attribute":
            value = expr(member.value)
            if LITERAL.match(value):
                return value
    return text


def params_text(fn, *, drop_self: bool) -> list[str]:
    kinds = []
    for p in fn.parameters:
        if drop_self and not kinds and p.name in ("self", "cls"):
            kinds.append(None)
            continue
        kinds.append(p)
    parts: list[str] = []
    seen_kw_only = False
    params = [p for p in kinds if p is not None]
    for idx, p in enumerate(params):
        kind = p.kind.value if p.kind else "positional or keyword"
        if kind == "keyword-only" and not seen_kw_only:
            if not any(q.kind and q.kind.value == "variadic positional" for q in params):
                parts.append("*")
            seen_kw_only = True
        text = p.name
        if kind == "variadic positional":
            text = "*" + text
        elif kind == "variadic keyword":
            text = "**" + text
        if p.annotation is not None:
            text += f": {expr(p.annotation)}"
        if p.default is not None and kind not in ("variadic positional", "variadic keyword"):
            default = default_text(p, fn)
            text += f" = {default}" if p.annotation is not None else f"={default}"
        parts.append(text)
        if kind == "positional-only":
            nxt = params[idx + 1] if idx + 1 < len(params) else None
            if nxt is None or (nxt.kind and nxt.kind.value != "positional-only"):
                parts.append("/")
    return parts


def signature(prefix: str, name: str, parts: list[str], returns: str = "") -> str:
    ret = f" -> {returns}" if returns else ""
    one = f"{prefix}{name}({', '.join(parts)}){ret}"
    if len(one) <= 88 or not parts:
        return one
    inner = "".join(f"    {p},\n" for p in parts)
    return f"{prefix}{name}(\n{inner}){ret}"


def fn_signature(fn, *, method: bool) -> str:
    prefix = "async def " if "async" in fn.labels else "def "
    return signature(prefix, fn.name, params_text(fn, drop_self=method), expr(fn.returns))


def fence(code: str) -> str:
    return f"```python\n{code}\n```\n"


# ---------------------------------------------------------------- rendering


def public_members(obj):
    return sorted(
        (m for n, m in obj.members.items() if not n.startswith("_") and not m.is_alias),
        key=lambda m: m.name.lower(),
    )


def docstring_of(obj) -> str:
    """The object's docstring, or for an attribute its `#:` comment block."""
    if obj.docstring and obj.docstring.value.strip():
        return obj.docstring.value
    if obj.kind.value != "attribute" or not obj.lineno:
        return ""
    lines = obj.parent.lines if obj.parent is not None else []
    comment: list[str] = []
    n = obj.lineno - 2
    while 0 <= n < len(lines) and lines[n].strip().startswith("#:"):
        comment.insert(0, lines[n].strip()[2:].strip())
        n -= 1
    return "\n".join(comment)


def attribute_rows(cls) -> list[tuple[str, str, str, str]]:
    """Fields and properties. An instance attribute that is only assigned in
    `__init__`, with no annotation or docstring, is left out: its meaning is
    the constructor parameter's, and a row would say nothing."""
    rows = []
    for m in public_members(cls):
        if m.kind.value == "attribute":
            class_level = "class-attribute" in m.labels or "dataclass-field" in m.labels
            doc = docstring_of(m)
            if not class_level and m.annotation is None and not doc:
                continue
            default = expr(m.value) if class_level else ""
            rows.append((m.name, expr(m.annotation), default, doc))
        elif m.kind.value == "function" and "property" in m.labels:
            rows.append((m.name, expr(m.returns), "", docstring_of(m)))
    return rows


def cell(s: str) -> str:
    return escape_prose(" ".join(s.split())).replace("|", "\\|")


def code_cell(s: str) -> str:
    if not s:
        return "—"
    return "`" + s.replace("|", "\\|") + "`"


class Page:
    def __init__(self) -> None:
        self.parts: list[str] = []
        self.undocumented: list[str] = []

    def add(self, text: str) -> None:
        self.parts.append(text)

    def doc(self, obj, path: str) -> None:
        text = docstring_of(obj)
        if text.strip():
            self.add(markdown(text) + "\n")
        else:
            self.undocumented.append(path)

    def text(self) -> str:
        return HEADER + "\n".join(self.parts).rstrip() + "\n"


def render_class(page: Page, name: str, cls, module_path: str) -> None:
    page.add(f"### {name}\n")
    bases = ", ".join(expr(b) for b in cls.bases)
    init = cls.members.get("__init__")
    if init is not None and init.kind.value == "function":
        sig = signature("class ", cls.name, params_text(init, drop_self=True))
    else:
        sig = f"class {cls.name}" + (f"({bases})" if bases else "")
    decorators = "".join(f"@{expr(d.value)}\n" for d in cls.decorators)
    page.add(fence(decorators + sig))
    if bases and init is not None:
        page.add(f"Bases: {', '.join(f'`{expr(b)}`' for b in cls.bases)}\n")
    page.doc(cls, f"{module_path}.{name}")
    rows = attribute_rows(cls)
    if rows:
        page.add("#### Attributes\n")
        page.add("| Name | Type | Default | Description |\n|---|---|---|---|")
        page.add("\n".join(f"| `{n}` | {code_cell(t)} | {code_cell(d)} | {cell(doc)} |" for n, t, d, doc in rows) + "\n")
    methods = [m for m in public_members(cls) if m.kind.value == "function" and "property" not in m.labels]
    if methods:
        page.add("#### Methods\n")
        for m in methods:
            static = "staticmethod" in m.labels or "classmethod" in m.labels
            page.add(f"##### {name}.{m.name}()\n")
            deco = "@classmethod\n" if "classmethod" in m.labels else "@staticmethod\n" if "staticmethod" in m.labels else ""
            page.add(fence(deco + fn_signature(m, method=not static or "classmethod" in m.labels)))
            page.doc(m, f"{module_path}.{name}.{m.name}")


def render_module(griffe, mod, path: str, children: list[str]) -> Page:
    page = Page()
    page.add(f"# {path}\n")
    if mod.docstring and mod.docstring.value.strip():
        page.add(markdown(mod.docstring.value) + "\n")
    if children:
        page.add("## Modules\n")
        page.add("| Module | Summary |\n|---|---|")
        page.add("\n".join(f"| [{c}]({page_link(c)}) | {summary_of(griffe, mod, c)} |" for c in children) + "\n")
    exports = mod.exports
    if exports is None:
        if children:
            return page
        sys.exit(f"gen-sdk-reference-python: {path} declares no __all__; its public API cannot be told apart")
    names = [e if isinstance(e, str) else e.name for e in exports]
    objs = []
    for name in names:
        member = mod.get_member(name) if name in mod.members else None
        if member is None:
            sys.exit(f"gen-sdk-reference-python: {path}.__all__ names {name}, which the module does not define")
        target = member.final_target if member.is_alias else member
        objs.append((name, target))
    groups = {"class": [], "function": [], "attribute": []}
    for name, obj in objs:
        groups.setdefault(obj.kind.value, []).append((name, obj))
    for kind, title in (("class", "Classes"), ("function", "Functions"), ("attribute", "Constants")):
        items = sorted(groups.get(kind, []), key=lambda x: x[0].lower())
        if not items:
            continue
        page.add(f"## {title}\n")
        for name, obj in items:
            where = obj.path if obj.path != f"{path}.{name}" else ""
            if kind == "class":
                render_class(page, name, obj, path)
            elif kind == "function":
                page.add(f"### {name}()\n")
                page.add(fence(fn_signature(obj, method=False)))
                page.doc(obj, f"{path}.{name}")
            else:
                page.add(f"### {name}\n")
                value = expr(obj.value)
                shown = value if value and len(value) <= 120 and "\n" not in value else "..."
                ann = f": {expr(obj.annotation)}" if obj.annotation is not None else ""
                page.add(fence(f"{name}{ann} = {shown}"))
                page.doc(obj, f"{path}.{name}")
            if where and name != obj.name:
                page.add(f"Defined as `{obj.path}`.\n")
    return page


def summary_of(griffe, parent, child_path: str) -> str:
    child = parent.modules_collection.get_member(child_path)
    return summary(child.docstring.value if child.docstring else "")


def generate() -> tuple[dict[str, str], list[str]]:
    griffe = load_griffe()
    ext = first_definition_wins(griffe)
    root = griffe.load(
        PACKAGE,
        search_paths=[str(PACKAGE_DIR)],
        allow_inspection=False,
        resolve_aliases=True,
        resolve_implicit=True,
        extensions=griffe.load_extensions(ext),
    )
    ext.restore(root)
    modules: list[tuple[str, list[str]]] = []
    for spec in PUBLIC_MODULES:
        if spec.endswith(".*"):
            pkg_path = spec[:-2]
            pkg = root.modules_collection.get_member(pkg_path)
            kids = sorted(f"{pkg_path}.{n}" for n, m in pkg.members.items() if m.is_module and not n.startswith("_"))
            modules.append((pkg_path, kids))
            modules += [(k, []) for k in kids]
        else:
            modules.append((spec, []))
    for path, _ in modules:
        mod = root.modules_collection.get_member(path)
        PACKAGES[path] = mod.is_package or mod.is_subpackage
    files: dict[str, str] = {}
    undocumented: list[str] = []
    for path, children in modules:
        mod = root.modules_collection.get_member(path)
        page = render_module(griffe, mod, path, children)
        files[page_file(path)] = page.text()
        undocumented += page.undocumented
    index = [
        HEADER,
        "# Python SDK reference\n\n",
        "The API of the `intutic-clawde` package (`pip install intutic-clawde`), generated from its source: "
        "every name a module exports in `__all__`, with its signature and docstring. "
        "The guides are the [clawde SDK](/reference/clawde-sdk) and the [Tool Gate SDK](/reference/gate-sdk).\n\n",
        "| Module | Summary |\n|---|---|\n",
    ]
    for path, _ in modules:
        mod = root.modules_collection.get_member(path)
        index.append(f"| [{path}]({page_link(path)}) | {summary(mod.docstring.value if mod.docstring else '')} |\n")
    files["index.md"] = "".join(index)
    sidebar = [{"text": "Overview", "link": f"{LINK_BASE}/"}] + [
        {"text": path, "link": page_link(path)} for path, _ in modules
    ]
    files["sidebar.json"] = json.dumps(sidebar, indent=2) + "\n"
    return files, undocumented


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail if the committed pages are stale; write nothing")
    ap.add_argument("--out", type=Path, default=OUT, help="output directory (default: %(default)s)")
    ap.add_argument("--report-undocumented", action="store_true", help="list exported names with no docstring")
    args = ap.parse_args()

    files, undocumented = generate()
    if args.report_undocumented:
        for name in undocumented:
            print(f"undocumented: {name}")

    out: Path = args.out
    present = {p.relative_to(out).as_posix() for p in out.rglob("*") if p.is_file()} if out.exists() else set()
    if args.check:
        stale = sorted(n for n, t in files.items() if n not in present or (out / n).read_text(encoding="utf-8") != t)
        extra = sorted(present - files.keys())
        if stale or extra:
            for n in stale:
                print(f"[FAIL] {out.relative_to(ROOT) if out.is_relative_to(ROOT) else out}/{n} is stale or missing")
            for n in extra:
                print(f"[FAIL] {out.relative_to(ROOT) if out.is_relative_to(ROOT) else out}/{n} is not generated by anything")
            print("The Python SDK reference does not match the source. Run `pnpm gen:sdk-reference` and commit the result.")
            return 1
        print(f"[PASS] Python SDK reference: {len(files)} files match the source")
        return 0

    out.mkdir(parents=True, exist_ok=True)
    for n in present - files.keys():
        (out / n).unlink()
    for n, t in files.items():
        (out / n).parent.mkdir(parents=True, exist_ok=True)
        (out / n).write_text(t, encoding="utf-8")
    print(f"Python SDK reference: wrote {len(files)} files to {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
