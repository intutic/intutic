#!/usr/bin/env node
/**
 * The SDK API reference on the docs site, generated from the SDKs' source.
 *
 * `pnpm gen:sdk-reference` writes apps/docs/reference/sdk/:
 *
 *   - <slug>/ for each TypeScript SDK in TS_PACKAGES: TypeDoc with
 *     typedoc-plugin-markdown and typedoc-vitepress-theme (exact versions
 *     pinned in the root package.json), one entry point per subpath in the
 *     package's `exports` (or its `types`/`main` when it has none), so the
 *     reference is the API a user can import and nothing else. Members marked
 *     `@internal` or `private` are left out. Each package gets a
 *     `typedoc-sidebar.json` that apps/docs/.vitepress/config.ts reads.
 *   - python/ for the Python SDK (packages/intutic-clawde): its public modules'
 *     `__all__`, rendered by gen-sdk-reference-python.py, which needs the
 *     package's Poetry environment (it pins griffe).
 *   - index.md, the overview of both.
 *
 * `--check` writes nothing and fails when the committed pages differ from
 * what the source produces. CI runs the TypeScript half in `lint:claims`
 * (`--check --only=ts`), and the Python half in the Python SDK job, which has
 * the Poetry environment (`gen-sdk-reference-python.py --check`).
 *
 * Why generated: the hand-kept API tables in reference/clawde-sdk.md and
 * reference/gate-sdk.md were a second copy of every signature and default,
 * kept in step by hand. Those pages are guides now and link here.
 *
 * Usage: node tools/scripts/gen-sdk-reference.mjs [--check] [--only=ts|python] [--report-undocumented]
 * Env:   INTUTIC_SDK_REFERENCE_PYTHON  a Python with griffe installed, instead
 *        of `poetry run python` in packages/intutic-clawde
 */
import { spawnSync } from 'node:child_process'
import { existsSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { basename, dirname, join, relative, sep } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..')
const DOCS = join(ROOT, 'apps', 'docs')
const OUT_REL = 'reference/sdk'

/** The TypeScript SDKs, and the directory under reference/sdk/ each is written to. */
export const TS_PACKAGES = [
  { dir: 'packages/gate-js', slug: 'gate', title: 'Tool Gate SDK', guide: '/reference/gate-sdk' },
  { dir: 'packages/clawde-sdk', slug: 'clawde', title: 'clawde SDK', guide: '/reference/clawde-sdk' },
]

const PYTHON_SCRIPT = 'tools/scripts/gen-sdk-reference-python.py'
const PYTHON_PACKAGE = 'packages/intutic-clawde'

const args = process.argv.slice(2)
const CHECK = args.includes('--check')
const REPORT_UNDOCUMENTED = args.includes('--report-undocumented')
const only = args.find((a) => a.startsWith('--only='))?.slice('--only='.length)
if (only && only !== 'ts' && only !== 'python') {
  console.error(`gen-sdk-reference: --only must be ts or python (got ${only})`)
  process.exit(2)
}

const HEADER =
  '<!-- Generated by tools/scripts/gen-sdk-reference.mjs. Do not edit: run `pnpm gen:sdk-reference`. -->\n\n'

/**
 * Each importable subpath of a package and the source file behind it:
 * `exports` when the package has it, else `types`/`main`. A dist path maps to
 * its source through the package's tsconfig rootDir/outDir.
 */
export function entryPoints(pkgDir) {
  const pkg = JSON.parse(readFileSync(join(pkgDir, 'package.json'), 'utf8'))
  const tsconfig = JSON.parse(readFileSync(join(pkgDir, 'tsconfig.json'), 'utf8'))
  const outDir = (tsconfig.compilerOptions?.outDir ?? 'dist').replace(/^\.\//, '')
  const rootDir = (tsconfig.compilerOptions?.rootDir ?? 'src').replace(/^\.\//, '')
  const targets = pkg.exports
    ? Object.entries(pkg.exports).map(([sub, t]) => [sub, typeof t === 'string' ? t : (t.types ?? t.import ?? t.default)])
    : [['.', pkg.types ?? pkg.main]]
  return targets.map(([sub, target]) => {
    const rel = target.replace(/^\.\//, '')
    if (!rel.startsWith(`${outDir}/`)) throw new Error(`${pkg.name}: export ${sub} (${target}) is not under ${outDir}/`)
    const src = `${rootDir}/${rel.slice(outDir.length + 1)}`.replace(/\.d\.ts$|\.js$/, '.ts')
    if (!existsSync(join(pkgDir, src))) throw new Error(`${pkg.name}: export ${sub} has no source at ${src}`)
    const subpath = sub.replace(/^\.\/?/, '')
    return {
      importPath: subpath ? `${pkg.name}/${subpath}` : pkg.name,
      // The module's directory under the package's reference: the subpath,
      // or `core` for the package root.
      slug: subpath || 'core',
      file: join(pkgDir, src),
    }
  })
}

/** Every file under `dir`, as forward-slash paths relative to it. */
function listFiles(dir) {
  if (!existsSync(dir)) return []
  const out = []
  const walk = (d) => {
    for (const e of readdirSync(d, { withFileTypes: true })) {
      const full = join(d, e.name)
      if (e.isDirectory()) walk(full)
      else out.push(relative(dir, full).split(sep).join('/'))
    }
  }
  walk(dir)
  return out.sort()
}

/** Paths that differ between two trees: missing, extra or changed. */
function diffTrees(want, have) {
  const a = listFiles(want)
  const b = new Set(listFiles(have))
  const problems = []
  for (const f of a) {
    if (!b.has(f)) problems.push(`${f} is missing`)
    else if (!readFileSync(join(want, f)).equals(readFileSync(join(have, f)))) problems.push(`${f} is stale`)
    b.delete(f)
  }
  for (const f of b) problems.push(`${f} is not generated by anything`)
  return problems
}

async function generateTs(docsRoot) {
  let td
  try {
    td = await import('typedoc')
  } catch {
    throw new Error('typedoc is not installed: run `pnpm install` at the repository root')
  }
  for (const p of TS_PACKAGES) {
    const pkgDir = join(ROOT, p.dir)
    if (!existsSync(join(pkgDir, 'package.json'))) {
      console.log(`[SKIP] ${p.dir} is not in this checkout`)
      continue
    }
    const entries = entryPoints(pkgDir)
    const titles = new Map(entries.map((e) => [e.slug, e.importPath]))
    const app = await td.Application.bootstrapWithPlugins({
      entryPoints: entries.map((e) => e.file),
      tsconfig: join(pkgDir, 'tsconfig.json'),
      plugin: ['typedoc-plugin-markdown', 'typedoc-vitepress-theme'],
      out: join(docsRoot, OUT_REL, p.slug),
      docsRoot,
      readme: 'none',
      // No "Defined in: file.ts:123" lines: they would make every unrelated
      // edit to an SDK source file a stale reference.
      disableSources: true,
      excludeInternal: true,
      excludePrivate: true,
      excludeProtected: true,
      excludeExternals: true,
      // VitePress compiles each page as a Vue template; this escapes markup
      // in doc comments that would otherwise be read as an element.
      sanitizeComments: true,
      useCodeBlocks: true,
      // A page per class; every other export is a section of its module's
      // page. A page per interface and type alias (some three hundred) made
      // the site's page index, which VitePress inlines into every page of the
      // site, several times its old size.
      membersWithOwnFile: ['Class'],
      // A module's page is titled with its import path; its URL uses the
      // subpath alone (an "@" and slashes would make nested directories).
      pageTitleTemplates: {
        index: '{projectName}',
        module: ({ name }) => titles.get(name) ?? name,
        member: '{kind}: {name}',
      },
      parametersFormat: 'table',
      interfacePropertiesFormat: 'table',
      classPropertiesFormat: 'table',
      enumMembersFormat: 'table',
      typeDeclarationFormat: 'table',
      propertyMembersFormat: 'table',
      sidebar: { autoConfiguration: true, format: 'vitepress', pretty: true, collapsed: true },
      validation: { notExported: false, invalidLink: true, notDocumented: REPORT_UNDOCUMENTED },
      logLevel: 'Warn',
    })
    const project = await app.convert()
    if (!project || app.logger.hasErrors()) throw new Error(`TypeDoc could not convert ${p.dir}`)
    app.validate(project)
    // Modules are named after their export subpath, not their file. TypeDoc
    // names each entry point's module after its file name (all sit in one
    // directory here), so that is the key.
    if (entries.length > 1) {
      const byFile = new Map(entries.map((e) => [basename(e.file, '.ts'), e.slug]))
      if (byFile.size !== entries.length) throw new Error(`${p.dir}: two entry points share a file name`)
      for (const mod of project.children ?? []) {
        const name = byFile.get(mod.name)
        if (!name) throw new Error(`${p.dir}: TypeDoc module ${mod.name} matches no export`)
        mod.name = name
      }
    }
    await app.generateOutputs(project)
    if (app.logger.hasErrors()) throw new Error(`TypeDoc could not render ${p.dir}`)
    if (entries.length > 1) {
      // The sidebar and the package's index name each module by its import
      // path too, in the order of the package's exports (the root first).
      const order = entries.map((e) => e.slug)
      const rank = (slug) => order.indexOf(slug)
      const file = join(docsRoot, OUT_REL, p.slug, 'typedoc-sidebar.json')
      const sidebar = JSON.parse(readFileSync(file, 'utf8'))
      sidebar.sort((a, b) => rank(a.link.split('/').at(-2)) - rank(b.link.split('/').at(-2)))
      for (const item of sidebar) item.text = titles.get(item.text) ?? item.text
      writeFileSync(file, JSON.stringify(sidebar, null, 2) + '\n')
      const index = join(docsRoot, OUT_REL, p.slug, 'index.md')
      const modules = entries.map((e) => `- [${e.importPath}](${e.slug}/index.md)`).join('\n')
      const text = readFileSync(index, 'utf8')
      const listed = /## Modules\n\n(- \[[^\n]*\n)+/
      if (!listed.test(text)) throw new Error(`${p.dir}: TypeDoc's index has no module list to rewrite`)
      writeFileSync(index, text.replace(listed, `## Modules\n\n${modules}\n`))
    }
  }
  writeFileSync(join(docsRoot, OUT_REL, 'index.md'), overviewPage())
}

function overviewPage() {
  const rows = TS_PACKAGES.filter((p) => existsSync(join(ROOT, p.dir, 'package.json'))).map((p) => {
    const pkg = JSON.parse(readFileSync(join(ROOT, p.dir, 'package.json'), 'utf8'))
    return `| [\`${pkg.name}\`](/${OUT_REL}/${p.slug}/) | TypeScript | [${p.title}](${p.guide}) |`
  })
  rows.push(`| [\`intutic-clawde\`](/${OUT_REL}/python/) | Python | [clawde SDK](/reference/clawde-sdk), [Tool Gate SDK](/reference/gate-sdk) |`)
  return (
    HEADER +
    '# SDK reference <Badge type="tip" text="Open-Core" />\n\n' +
    'The API of each Intutic SDK, generated from its source: every exported class, function, type and constant, ' +
    'with its signature and doc comment. The guides explain how the pieces fit together; this is the list.\n\n' +
    '| Package | Language | Guide |\n|---|---|---|\n' +
    rows.join('\n') +
    '\n'
  )
}

function pythonCommand() {
  const explicit = process.env.INTUTIC_SDK_REFERENCE_PYTHON
  if (explicit) return { cmd: explicit, pre: [], cwd: ROOT, script: join(ROOT, PYTHON_SCRIPT) }
  const poetry = spawnSync('poetry', ['--version'], { encoding: 'utf8' })
  if (poetry.status !== 0) {
    throw new Error(
      'the Python half needs Poetry (or INTUTIC_SDK_REFERENCE_PYTHON set to a Python with griffe): ' +
        `cd ${PYTHON_PACKAGE} && poetry install --with dev`,
    )
  }
  return { cmd: 'poetry', pre: ['run', 'python'], cwd: join(ROOT, PYTHON_PACKAGE), script: join(ROOT, PYTHON_SCRIPT) }
}

function runPython() {
  if (!existsSync(join(ROOT, PYTHON_PACKAGE, 'pyproject.toml'))) {
    console.log(`[SKIP] ${PYTHON_PACKAGE} is not in this checkout`)
    return true
  }
  const { cmd, pre, cwd, script } = pythonCommand()
  const r = spawnSync(cmd, [...pre, script, ...(CHECK ? ['--check'] : [])], { cwd, stdio: 'inherit' })
  if (r.error) throw r.error
  return r.status === 0
}

async function main() {
  let ok = true
  if (only !== 'python') {
    const tmp = mkdtempSync(join(tmpdir(), 'sdk-reference-'))
    try {
      await generateTs(tmp)
      const fresh = join(tmp, OUT_REL)
      const targets = [...TS_PACKAGES.map((p) => p.slug), 'index.md']
      if (CHECK) {
        const problems = []
        for (const t of targets) {
          const want = join(fresh, t)
          const have = join(DOCS, OUT_REL, t)
          if (t.endsWith('.md')) {
            if (!existsSync(have)) problems.push(`${t} is missing`)
            else if (!readFileSync(want).equals(readFileSync(have))) problems.push(`${t} is stale`)
          } else if (existsSync(want)) {
            problems.push(...diffTrees(want, have).map((m) => `${t}/${m}`))
          }
        }
        if (problems.length) {
          for (const m of problems) console.log(`[FAIL] apps/docs/${OUT_REL}/${m}`)
          console.log('The TypeScript SDK reference does not match the source. Run `pnpm gen:sdk-reference` and commit the result.')
          ok = false
        } else {
          console.log(`[PASS] TypeScript SDK reference matches the source (${TS_PACKAGES.map((p) => p.slug).join(', ')})`)
        }
      } else {
        mkdirSync(join(DOCS, OUT_REL), { recursive: true })
        for (const t of targets) {
          const want = join(fresh, t)
          const have = join(DOCS, OUT_REL, t)
          if (!existsSync(want)) continue
          rmSync(have, { recursive: true, force: true })
          if (t.endsWith('.md')) writeFileSync(have, readFileSync(want))
          else for (const f of listFiles(want)) {
            mkdirSync(dirname(join(have, f)), { recursive: true })
            writeFileSync(join(have, f), readFileSync(join(want, f)))
          }
        }
        console.log(`TypeScript SDK reference: wrote apps/docs/${OUT_REL}/{${targets.join(',')}}`)
      }
    } finally {
      rmSync(tmp, { recursive: true, force: true })
    }
  }
  if (only !== 'ts') ok = runPython() && ok
  process.exit(ok ? 0 : 1)
}

main().catch((err) => {
  console.error(`gen-sdk-reference: ${err.message}`)
  process.exit(1)
})
