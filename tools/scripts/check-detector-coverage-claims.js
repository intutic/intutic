#!/usr/bin/env node
/**
 * The published detector-coverage figure must match the generated baseline.
 *
 * `apps/docs/compare/portkey.md` publishes the one number in the product with a
 * reproducible source: the false-positive rate, plus the caveat naming how much
 * of the detector registry it actually reaches. That caveat read **"6 of 22
 * detectors"** while `packages/proxy/tests/corpus/BASELINE.txt` — generated from
 * the live registry at test time, precisely so it cannot go stale — said **18 of
 * 25 are not-measured**, i.e. 7 of 25.
 *
 * Both numbers were wrong, and the supporting arithmetic in the same sentence
 * ("ten read fields no trajectory carries; the rest…") only closed on 22. So a
 * page whose entire argument is "here is a number you can check" carried a
 * denominator nobody had checked.
 *
 * The baseline is regenerated by the Rust test from `DetectorRegistry::
 * with_defaults()`. Registering a detector therefore moves the true denominator,
 * and nothing connected that to the published prose. This does.
 *
 * Exit 1 on any mismatch or on any file it cannot read — a gate that cannot find
 * its inputs must not report success.
 */
import { readFileSync, existsSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..')
const BASELINE = join(ROOT, 'packages/proxy/tests/corpus/BASELINE.txt')
const PAGES = [join(ROOT, 'apps/docs/compare/portkey.md')]

function fail(msg) {
  console.error(`[FAIL] ${msg}`)
  process.exit(1)
}

if (!existsSync(BASELINE)) {
  fail(
    `${BASELINE} is missing.\n` +
      'It is generated by packages/proxy/tests/anomaly_corpus_test.rs. Run:\n' +
      '    cargo test --package intutic-proxy --test anomaly_corpus_test',
  )
}

const baseline = readFileSync(BASELINE, 'utf8')

// "18 of 25 are not-measured."
const m = baseline.match(/(\d+)\s+of\s+(\d+)\s+are\s+not-measured/i)
if (!m) {
  fail(
    `could not find the "N of M are not-measured" line in ${BASELINE}.\n` +
      'That line is the source of truth for every published coverage figure. If its\n' +
      'wording changed, update this gate deliberately — do not delete the assertion.',
  )
}

const notMeasured = Number(m[1])
const total = Number(m[2])
const measured = total - notMeasured

if (!Number.isInteger(measured) || measured <= 0 || measured >= total) {
  fail(`baseline arithmetic is nonsense: ${notMeasured} of ${total} not-measured`)
}

// Cross-check against the per-detector table, so a hand-edited summary line
// cannot satisfy this gate on its own.
const rows = baseline
  .split('\n')
  .map((l) => l.split('|'))
  .filter((c) => c.length > 2)
  .map((c) => [c[0].trim(), c[1].trim()])
  // Drop the header (`detector_id | measured | …`) and the rule beneath it. The
  // header's second cell is the literal word `measured`, which otherwise counts
  // as a measured detector and inflates the denominator by one.
  .filter(([id, kind]) => /^[a-z][a-z0-9_]*$/.test(id) && id !== 'detector_id' && kind)
  .map(([, kind]) => kind)
const tableNotMeasured = rows.filter((v) => v === 'not-measured').length
const tableTotal = rows.length
if (tableTotal !== total || tableNotMeasured !== notMeasured) {
  fail(
    `${BASELINE} contradicts itself: the summary says ${notMeasured} of ${total} ` +
      `not-measured, the table has ${tableNotMeasured} of ${tableTotal}.`,
  )
}

let offences = 0
let checked = 0

for (const page of PAGES) {
  if (!existsSync(page)) fail(`${page} is missing — this gate asserted nothing.`)
  const text = readFileSync(page, 'utf8')

  // Any "N of M detectors" claim on the page must agree with the baseline.
  const claims = [...text.matchAll(/covers\s+\*{0,2}(\d+)\s+of\s+(\d+)\s+detectors/gi)]
  if (claims.length === 0) {
    fail(
      `${page} publishes the false-positive rate but no "covers N of M detectors" ` +
        'caveat.\nA rate without its reach is the marketing claim this gate exists to stop.',
    )
  }
  checked += claims.length

  for (const c of claims) {
    const [gotMeasured, gotTotal] = [Number(c[1]), Number(c[2])]
    if (gotMeasured !== measured || gotTotal !== total) {
      console.error(
        `[FAIL] ${page}: published "covers ${gotMeasured} of ${gotTotal} detectors", ` +
          `baseline says ${measured} of ${total}.`,
      )
      offences += 1
    }
  }
}

if (checked === 0) fail('no coverage claim was checked. This gate asserted nothing.')

if (offences > 0) {
  console.error(
    `\nThe baseline is generated from the detector registry; the prose is not. ` +
      `Update the\npage to match, or explain in the page why it should differ.`,
  )
  process.exit(1)
}

console.log(
  `[PASS] published detector coverage (${measured} of ${total}) matches the generated baseline.`,
)
